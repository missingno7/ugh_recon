"""Generate c/ugh_sym.h from the fresh plain TLINK map/TASM symbol tables.

The names ledger supplies spelling and expected coordinates, never placement.
No oracle executable is read. Missing, ambiguous, stale or moved symbols are errors.
"""
import argparse
import json
import re
from pathlib import Path
from common import ROOT, MZ, sha256

PLAIN = ROOT / 'build/link/plain'
LOAD = 0x1010
FRAMES = dict(GAME=0x13B, SOUND=0x664, C=0x878, TIMER=0xA32,
              DGROUP=0x5C09, ZERO=0xA67, CDATA=0x1A37)


def read_symbols(directory=PLAIN):
    receipt = json.loads((directory / 'build.json').read_text())
    if receipt['variant'] != 'plain':
        raise ValueError('only the plain build is a translation oracle')
    recorded={Path(p).as_posix() for p in receipt['source_sha256'] if Path(p).parts[0]=='src'}
    maintained={p.relative_to(ROOT).as_posix() for p in (ROOT/'src').rglob('*')
                if p.is_file() and p.suffix.lower() in ('.asm','.c','.h','.inc')}
    if recorded != maintained:
        raise ValueError('plain build source set drift; run python tools/verify.py')
    for path, digest in receipt['source_sha256'].items():
        if sha256((ROOT / path).read_bytes()) != digest:
            raise ValueError(f'stale plain build: {path}; run python tools/verify.py')
    mz = MZ((directory / 'UGH.EXE').read_bytes())
    lock = json.loads((ROOT / 'metadata/oracle.json').read_text())['expanded']
    if sha256(mz.image) != lock['image_sha256']:
        raise ValueError('rebuilt load image drift; run python tools/verify.py')
    if mz.identity()['reloc_sorted_sha256'] != lock['reloc_sorted_sha256']:
        raise ValueError('rebuilt relocation sites drift; run python tools/verify.py')
    text = (directory / 'UGH.MAP').read_text()
    segments = {m[3].upper(): int(m[1], 16) for m in re.finditer(
        r'^\s*([0-9A-F]+)H\s+[0-9A-F]+H\s+([0-9A-F]+)H\s+(\S+)\s+\S+\s*$', text, re.M)}
    publics = text.split('Publics by Name', 1)[1].split('Publics by Value', 1)[0]
    found = {}
    def add(name, linear):
        found.setdefault(name.upper(), set()).add(linear)
    for m in re.finditer(r'^\s*([0-9A-F]{4}):([0-9A-F]{4})\s+(?:idle\s+)?(\S+)', publics, re.M):
        add(m[3], int(m[1], 16)*16 + int(m[2], 16))
    contributions = {}
    for m in re.finditer(r'^\s*([0-9A-F]{4}):([0-9A-F]{4})\s+[0-9A-F]+\s+C=\S+\s+S=(\S+)\s+G=\S+\s+M=(\S+)', text, re.M):
        module = m[4].upper().split('.')[0]
        contributions[module, m[3].upper()] = int(m[1], 16)*16 + int(m[2], 16)
    # Local labels and relocatable EQUs are not necessarily TLINK publics.
    for path in sorted(directory.glob('*.LST')):
        table = path.read_text().split('Symbol Name', 1)[-1]
        # TASM prints the rest of a >30-character name on the next line.
        table = re.sub(r'(?m)^([A-Z_?$@][\w?$@]*)([ \t]+\w+[ \t]+[\w$]+:[0-9A-F]{4})[ \t]*\n([A-Z_?$@][\w?$@]*)[ \t]*$',
                       lambda m: m[1] + m[3] + m[2], table)
        for m in re.finditer(r'^([A-Z_?$@][\w?$@]*)\s+\w+\s+([\w$]+):([0-9A-F]{4})\s*$', table, re.M):
            base = contributions.get((path.stem.upper(), m[2]), segments.get(m[2]))
            if base is not None:
                add(m[1], base + int(m[3], 16))
    ledger = json.loads((ROOT / 'metadata/names.json').read_text())['symbols']
    result = {}
    for key, rec in ledger.items():
        frame, off = (int(x, 16) for x in rec['address'].split(':'))
        want = frame*16 + off
        candidates = set()
        for spelling in rec['spellings']:
            candidates |= found.get(spelling['name'].upper(), set())
            if spelling['module'] == 'C' and not spelling.get('decorated'):
                candidates |= found.get('_' + spelling['name'].upper(), set())
        # Names such as loc_00E4 are module local. Their matching physical symbol
        # must exist; unrelated same-spelled locals can coexist in other segments.
        if want not in candidates:
            raise ValueError(f'{key}: missing/moved build symbol {rec["name"]}; got {sorted(candidates)}')
        owners = [name for name, value in FRAMES.items() if value == frame]
        owner = owners[0] if owners else f'B{frame:04X}'
        aliases = {(owner, rec['name'])} | {(s['module'], s['name']) for s in rec['spellings']}
        for module, name in aliases:
            if not re.fullmatch(r'[A-Za-z_]\w*', name):
                continue
            q = f'{module}:{name}'
            value = dict(frame=frame, offset=off, linear=want, identity=key)
            if q in result and result[q]['linear'] != want:
                raise ValueError('ambiguous generated symbol: ' + q)
            result[q] = value
    return mz, result


def generate(check=False):
    mz, symbols = read_symbols()
    lines = ['/* Generated by tools/cgen.py: TLINK map + TASM listings, checked against names.json. */',
             '#ifndef UGH_SYM_H', '#define UGH_SYM_H', f'#define UGH_LOAD 0x{LOAD:04X}u']
    for module, frame in FRAMES.items():
        lines += [f'#define UGH_FRAME_{module} 0x{frame:04X}u',
                  f'#define UGH_SEG_{module} (UGH_LOAD + UGH_FRAME_{module})']
    for name, rec in sorted(symbols.items()):
        token = name.replace(':', '_')
        lines += [f'#define UGH_O_{token} 0x{rec["offset"]:04X}u',
                  f'#define UGH_S_{token} (UGH_LOAD + 0x{rec["frame"]:04X}u)']
    lines += ['#endif', '']
    out = ROOT / 'c/ugh_sym.h'
    content = '\n'.join(lines)
    if check:
        if not out.exists() or out.read_text() != content:
            raise ValueError('c/ugh_sym.h stale; run python tools/cgen.py')
    elif not out.exists() or out.read_text() != content:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)
    manifest = dict(image_sha256=sha256(mz.image), symbols=symbols)
    target = ROOT / 'build/c/symbols.json'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(manifest, indent=2) + '\n')
    return symbols


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    try:
        print(f'{len(generate(a.check))} checked symbol aliases; c/ugh_sym.h')
    except (ValueError, KeyError, FileNotFoundError) as e:
        p.exit(2, f'cgen: {e}\n')
